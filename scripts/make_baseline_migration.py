"""Write pubbank/migrations/001_baseline.sql: the database structure (no data) as it is on this computer today.
A brand-new installation starts from this file; an existing database (like the pilot's) is recognised and left alone.
  .venv/Scripts/python.exe scripts/make_baseline_migration.py
Run it again only if you want to regenerate the baseline before any other installation exists.
"""
import os
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from dotenv import load_dotenv  # noqa: E402

load_dotenv(ROOT / ".env")
from pubbank.db import pg_bin  # noqa: E402

u = urlparse(os.environ["DATABASE_URL"])
env = {**os.environ, "PGPASSWORD": u.password or ""}
r = subprocess.run([str(pg_bin() / "pg_dump.exe"), "-h", u.hostname or "localhost", "-p", str(u.port or 5432), "-U", u.username or "postgres",
                    "-d", u.path.lstrip("/"), "--schema-only", "--no-owner", "--no-privileges", "--no-comments"],
                   env=env, capture_output=True, text=True, encoding="utf-8")
if r.returncode:
    sys.exit(r.stderr[:500])
text = r.stdout
# keep only plain SQL statements this app's database driver can run: drop psql meta-commands and session settings
lines = [ln for ln in text.splitlines() if not ln.startswith("\\") and not ln.startswith("SET ") and "set_config('search_path'" not in ln]
sql = "\n".join(lines)
sql = re.sub(r"\n{3,}", "\n\n", sql).strip() + "\n"
sql = sql.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ").replace("CREATE INDEX ", "CREATE INDEX IF NOT EXISTS ").replace("CREATE UNIQUE INDEX ", "CREATE UNIQUE INDEX IF NOT EXISTS ")
header = "-- Baseline structure of the publication bank database (generated by scripts/make_baseline_migration.py).\n"
out = ROOT / "pubbank" / "migrations" / "001_baseline.sql"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(header + sql, encoding="utf-8")
print("wrote", out, f"({len(sql.splitlines())} lines)")
print("tables:", re.findall(r"CREATE TABLE IF NOT EXISTS (\S+)", sql))
